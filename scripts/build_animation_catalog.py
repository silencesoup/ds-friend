def main():
    folder = ROOT/'vendor/dsh-pet'
    output = folder/'animation_descriptions.json'
    if output.exists():
        raise SystemExit('Catalog exists; edit it in place instead of overwriting user descriptions.')
    clips = []
    for path in sorted((folder/'upstream/assets/webm').glob('*.webm')):
        name = path.stem
        if name not in DETAILS:
            raise ValueError('Missing description: '+name)
        description,mood,keywords = DETAILS[name]
        reserved = name.startswith(('余额-','睡觉-')) or name in ('被鼠标拖拽悬空反馈','原地左转奔跑')
        clips.append({'id':name,'file':path.name,'description':description,'moods':[mood],
                      'keywords':keywords.split(','),'model_selectable':not reserved})
    output.write_text(json.dumps({'schema':1,'upstream_version':'0.4.1','clips':clips},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'{len(clips)} clips described')

if __name__=='__main__':
    main()
